// One-off: extract HK district land rings for the stay-area schematic map.
// Source: https://github.com/hupili/geohk census2001/dc_land.lowres.geo.json
// (data.gov.hk district boundaries). Run: node scripts/gen-stay-map-hk.mjs
import fs from 'node:fs'

const fc = JSON.parse(fs.readFileSync(new URL('../hk-dc.json', import.meta.url), 'utf8'))

// Districts kept for the harbour-area map (all 18 kept if they intersect the crop).
const BBOX = { lng0: 114.06, lng1: 114.27, lat0: 22.235, lat1: 22.365 }
const MIN_D2 = 0.0009 ** 2

const simplify = (ring) => {
  const out = [ring[0]]
  for (let i = 1; i < ring.length; i++) {
    const [x, y] = ring[i]
    const [px, py] = out[out.length - 1]
    if ((x - px) ** 2 + (y - py) ** 2 >= MIN_D2) out.push(ring[i])
  }
  return out
}
const inBbox = (ring) =>
  ring.some(([x, y]) => x >= BBOX.lng0 && x <= BBOX.lng1 && y >= BBOX.lat0 && y <= BBOX.lat1)

const out = []
for (const f of fc.features) {
  const geom = f.geometry
  const polys = geom.type === 'MultiPolygon' ? geom.coordinates : [geom.coordinates]
  const rings = []
  for (const poly of polys) {
    const ext = simplify(poly[0]).map(([x, y]) => [+x.toFixed(5), +y.toFixed(5)])
    if (ext.length >= 4 && inBbox(ext)) rings.push(ext)
  }
  if (rings.length) out.push({ name: f.properties.DC_CHIN, eng: f.properties.DC_ENG, rings })
}

fs.writeFileSync(
  new URL('../src/content/stayMapGeoHK.ts', import.meta.url),
  `// Generated by scripts/gen-stay-map-hk.mjs from data.gov.hk district boundaries (geohk lowres).
// Do not hand-edit; real WGS84 coordinates.
export const HK_LAND: { name: string; eng: string; rings: [number, number][][] }[] = ${JSON.stringify(out)}
`,
)
console.log('districts:', out.length, 'rings:', out.reduce((n, d) => n + d.rings.length, 0), 'points:', out.reduce((n, d) => n + d.rings.reduce((m, r) => m + r.length, 0), 0))
